export interface CategoryGuess {
  category: string;
  menu?: string;
}

export function guessCategory(...texts: (string | undefined)[]): CategoryGuess | null {
  const hay = texts.filter(Boolean).join(' ').replace(/\s+/g, '').toLowerCase();
  if (!hay) return null;
  for (const [keywords, category, menu] of RULES) {
    // 한 글자 키워드('죽', '난')는 이름 끝에 올 때만 (예: '본죽' O, '죽전' X)
    if (keywords.some((k) => (k.length === 1 ? hay.endsWith(k) : hay.includes(k.toLowerCase())))) {
      return { category, menu };
    }
  }
  return null;
}
